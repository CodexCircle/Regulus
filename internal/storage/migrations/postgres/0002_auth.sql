-- Local accounts and their login sessions.
-- citext compares without regard to case, like COLLATE NOCASE in SQLite. It is
-- a trusted extension (PostgreSQL 13 and later), so the owner of the database
-- can create it. It goes in public, which stays on the search path of the hub
-- even when the tables live in another schema.
CREATE EXTENSION IF NOT EXISTS citext WITH SCHEMA public;

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      CITEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    role          TEXT NOT NULL CHECK (role IN ('admin', 'viewer')),
    created_at    TEXT NOT NULL
);

-- Only the SHA-256 of the session token is stored, so a leaked database does
-- not hand out valid sessions.
CREATE TABLE sessions (
    token_hash TEXT PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    created_at TEXT NOT NULL,
    expires_at TEXT NOT NULL
);

CREATE INDEX sessions_user ON sessions (user_id);
CREATE INDEX sessions_expires ON sessions (expires_at);
